export const LANGUAGES = Object.keys(STRINGS);

// The saved choice wins; otherwise the first browser language we have strings for.
export function pickLanguage(saved, browserLanguages) {
  if (LANGUAGES.includes(saved)) return saved;
  const match = browserLanguages.map((l) => l.slice(0, 2).toLowerCase()).find((l) => LANGUAGES.includes(l));
  return match ?? 'en';
}
